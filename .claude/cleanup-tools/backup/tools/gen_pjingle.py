"""The win jingle, no samples: writes game/pjingle.inc for the tone generators of the PSG (period table, chords, rows of 3 bytes: channel A, B, C)
and for the SCC (five voices, rows of 5 bytes).
PSG row bytes: 0 = go on, 1.. = note (index in the table), 80h + k = chord k (fast arpeggio: one note of the chord per frame), 0FEh = silence,
in the first byte 0FDh = start the final fade, 0FFh = end.  One row is 5 frames + 1 at 50 Hz (6 + 1 at 60 Hz).  python tools/gen_pjingle.py"""
import os
import math

HERE = os.path.dirname(os.path.abspath(__file__))
PSG = 111860.78                    # 1.7897 MHz / 16
SEMI = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def freq(n):
    m = 12 * (int(n[-1]) + 1) + SEMI[n[0]] + (1 if '#' in n else 0)
    return 440.0 * 2 ** ((m - 69) / 12)


# (row, channel, note or chord (tuple of 3 notes))
C_ = ('C5', 'E5', 'G5')
C_LOW = ('G4', 'C5', 'E5')
C_HI = ('C6', 'E6', 'G6')
F_ = ('A4', 'C5', 'F5')
G_ = ('B4', 'D5', 'G5')
SCORE = [
    # melody
    (0, 0, 'C5'), (2, 0, 'E5'), (4, 0, 'G5'), (6, 0, 'C6'), (8, 0, 'G5'), (10, 0, 'C6'), (12, 0, 'E6'), (14, 0, 'G6'),
    (16, 0, 'F5'), (18, 0, 'A5'), (20, 0, 'C6'), (22, 0, 'G5'), (24, 0, 'B5'), (26, 0, 'D6'), (28, 0, C_HI),
    (34, 0, 'E6'), (35, 0, 'G6'), (36, 0, 'C7'),
    # accompaniment: the chord as a fast arpeggio
    (0, 1, C_), (16, 1, F_), (22, 1, G_), (28, 1, C_LOW),
    # bass
    (0, 2, 'C3'), (6, 2, 'C3'), (12, 2, 'C3'), (16, 2, 'F3'), (22, 2, 'G3'), (28, 2, 'C3'),
]
FADE = 38                          # the final fade starts here
END = 46


def make():
    notes = []
    chords = []

    def code(x):
        if isinstance(x, tuple):
            if x not in chords:
                chords.append(x)
            return 0x80 + chords.index(x) + 1
        if x not in notes:
            notes.append(x)
        return notes.index(x) + 1
    rows = {}
    for r, ch, n in SCORE:
        rows.setdefault(r, [0, 0, 0])[ch] = code(n)
    rows.setdefault(FADE, [0, 0, 0])[0] = 0xFD
    out = [rows.get(r, [0, 0, 0]) for r in range(END)]
    out.append([0xFF, 0, 0])
    s = '; generated by tools/gen_pjingle.py\npj_tab:\n'
    for n in notes:
        s += '        dw %d                          ; %s\n' % (round(PSG / freq(n)), n)
    s += 'pj_chords:\n'
    for c in chords:
        s += '        dw %s                ; %s\n' % (','.join(str(round(PSG / freq(n))) for n in c), ' '.join(c))
    s += 'pj_data:\n'
    for r in out:
        s += '        db %s\n' % ','.join(str(v) for v in r)
    return s


# ---- the same fanfare for the SCC: five voices (melody, a real three note chord, bass), rows of 5 bytes: A, B1, B2, B3, C
SCC_A = [(0, 'C5'), (2, 'E5'), (4, 'G5'), (6, 'C6'), (8, 'G5'), (10, 'C6'), (12, 'E6'), (14, 'G6'), (16, 'F5'), (18, 'A5'), (20, 'C6'), (22, 'G5'), (24, 'B5'),
         (26, 'D6'), (28, 'C6'), (34, 'E6'), (35, 'G6'), (36, 'C7')]
SCC_B = [(0, C_), (16, F_), (22, G_), (28, C_LOW)]
SCC_C = [(0, 'C3'), (6, 'C3'), (12, 'C3'), (16, 'F3'), (22, 'G3'), (28, 'C3')]


def make_scc():
    notes = []

    def code(n):
        if n not in notes:
            notes.append(n)
        return notes.index(n) + 1
    rows = {}
    for r, n in SCC_A:
        rows.setdefault(r, [0] * 5)[0] = code(n)
    for r, ch in SCC_B:
        for k, n in enumerate(ch):
            rows.setdefault(r, [0] * 5)[1 + k] = code(n)
    for r, n in SCC_C:
        rows.setdefault(r, [0] * 5)[4] = code(n)
    rows.setdefault(FADE, [0] * 5)[0] = 0xFD
    out = [rows.get(r, [0] * 5) for r in range(END)] + [[0xFF, 0, 0, 0, 0]]
    s = 'sj_tab:                                ; SCC periods (the frequency is 111861 / (period + 1))\n'
    for n in notes:
        s += '        dw %d                          ; %s\n' % (round(111861 / freq(n)) - 1, n)
    s += 'sj_data:\n'
    for r in out:
        s += '        db %s\n' % ','.join(str(v) for v in r)
    # wave forms: 32 signed bytes.  1 = melody (pulse, 25 %), 2 = chord (soft, two harmonics), 3 = triangle (bass and the third chord note)
    G = 0.4                                                     # the music of the SCC is quiet (about a third of the full scale): the jingle must not stand out
    w1 = [int(round(100 * G)) if i < 8 else -int(round(100 * G)) for i in range(32)]
    w2 = [int(round(70 * G * (math.sin(2 * math.pi * i / 32) + math.sin(6 * math.pi * i / 32) / 3) / 1.2)) for i in range(32)]
    w3 = [int(round(110 * G * (1 - abs(((i + 4) % 32) - 16) / 8))) for i in range(32)]
    for nm, w in (('sj_w1', w1), ('sj_w2', w2), ('sj_w3', w3)):
        s += nm + ':\n        db ' + ','.join(str(v & 0xFF) for v in w) + '\n'
    return s


if __name__ == '__main__':
    open(os.path.join(os.path.dirname(HERE), 'game', 'pjingle.inc'), 'w').write(make() + make_scc())
    print('ok')
