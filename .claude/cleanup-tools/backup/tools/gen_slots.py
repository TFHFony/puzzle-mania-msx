def fmt(line, i=0):
    line = re.sub(r'\.(c0|c1|c2|n1|n2|n3|n4|n5|pae|pbe|pce|pde)\b', lambda m: '.%s_%d' % (m.group(1), i), line)
    if line.endswith(':') and line.startswith('.'):
        return line
    if ': ' in line and line.split(':')[0].startswith('.'):
        lab, ins = line.split(': ', 1)
        return '%-8s%s' % (lab + ':', ins)
    if line.startswith('MCMP') or line.startswith('MSAMPLE'):
        return '        ' + line
    return '        ' + line


