"""Test ROM (ASCII16, 4 MB): only the PM logo with its music, the real title video loop in four speeds (0 / 4 / 8 / 11 cycles less per loop of 446), keys 1..4.
For real hardware: a MSX2+ / turbo R runs the loop about 1.8 % slow (VDP wait states), so the music is a bit low with 446 and about right with 438.
   python build_logomusic.py [--out file] [--frames N]"""
import os, sys, subprocess, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(PROJ, 'tools'))
SJ = r'F:\MSX Projects\Dev27\.claude\msx-video-tools\sjasmplus\sjasmplus-1.24.0.win\sjasmplus.exe'
arg = lambda n, d=None: sys.argv[sys.argv.index(n) + 1] if n in sys.argv else d
OUT = arg('--out', os.path.join(PROJ, 'PM_LogoMusic_4MB_ASCII16.rom'))
W = os.path.join(HERE, 'lm'); os.makedirs(W, exist_ok=True)

def main():
    import title_video, gen_tvplay
    nf = int(arg('--frames', '0')) or title_video.frames_of(os.path.join(PROJ, 'PM-Menu.mp3'))
    tvw, tvb, tvn, tvdatas = title_video.build(os.path.join(PROJ, 'Videos', 'STEF-1.mp4'), title_video.TITLE_START, nf, None, None, os.path.join(PROJ, 'PM-Menu.mp3'), encode=title_video.encode_parallel)
    assert len(tvb) == tvn and all(len(b) == 16384 for b in tvb)
    TVBANK = 1
    PLRBK = TVBANK + tvn
    assert PLRBK < 256
    txt = '; GENERATED by build_logomusic.py: the title video loop in four speeds (D = cycles less per loop)\n'
    for d in (0, 4, 8, 11):
        gen_tvplay.main(d, 'tvd%d_' % d, 'tvplay_tmp.inc')
        txt += open(os.path.join(PROJ, 'game', 'tvplay_tmp.inc')).read()
    os.remove(os.path.join(PROJ, 'game', 'tvplay_tmp.inc'))
    open(os.path.join(W, 'tvplay_var.inc'), 'w').write(txt)
    open(os.path.join(W, 'lmcfg.inc'), 'w').write('TVFRAMES equ %d\nTVBANK equ %d\nPLRBK equ %d\n' % (tvn, TVBANK, PLRBK))
    shutil.copy(os.path.join(HERE, 'logomusic.asm'), os.path.join(W, 'logomusic.asm'))
    r = subprocess.run([SJ, '--nologo', '--lst=logomusic.lst', '--sym=logomusic.sym', 'logomusic.asm'], cwd=W, capture_output=True, text=True)
    print(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    code = open(os.path.join(W, 'code.bin'), 'rb').read()
    assert len(code) == 16384
    plr = open(os.path.join(PROJ, 'game', 'plr.bin'), 'rb').read()               # the player block of the last build: the volume tables come first
    assert len(plr) >= 768
    tab = plr[:768] + bytes([0xFF]) * (16384 - 768)
    rom = code + b''.join(tvb) + tab
    rom += bytes([0xFF]) * (4 * 1024 * 1024 - len(rom))
    open(OUT, 'wb').write(rom)
    import hashlib
    print(OUT, len(rom), 'bytes,', tvn, 'frames, tables in bank', PLRBK, ', md5', hashlib.md5(rom).hexdigest())


if __name__ == '__main__':
    main()
