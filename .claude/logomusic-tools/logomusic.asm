; PM logo + music test ROM (ASCII16, standalone): the real title video of Puzzle Mania (tools/gen_tvplay.py) in four loop speeds
; bank 0 = this code, banks TVBANK.. = the stream (one video frame with its music per bank), bank PLRBK = the PSG volume tables (first 768 bytes of the player block)
        DEVICE NOSLOT64K
        INCLUDE "lmcfg.inc"            ; TVFRAMES, TVBANK, PLRBK (generated by build_logomusic.py)
TABHI   equ 0xC4
tv_f    equ 0xC1EF
bankdummy equ 0xC1EC
lsel    equ 0xC1E0
        MACRO BANKHI addr
        ld (bankdummy),a
        ENDM
        ORG 0x4000
        db "AB"
        dw init
        dw 0,0,0,0,0,0
        ORG 0x4010
init:   di
        ld sp,0xF380
        ld hl,0xC000
        ld de,0xC001
        ld bc,0x12FF
        ld (hl),0
        ldir
        xor a
        ld (0x6000),a                   ; ASCII16: page 1 = bank 0
        ld a,PLRBK
        ld (0x7000),a                   ; page 2 = the bank with the tables
        call 0x0138                     ; RSLREG: page 2 = our cartridge slot (the same as page 1)
        rrca
        rrca
        and 3
        ld c,a
        ld b,0
        ld hl,0xFCC1
        add hl,bc
        or (hl)
        ld c,a
        inc hl
        inc hl
        inc hl
        inc hl
        ld a,(hl)
        and 0x0C
        or c
        ld h,0x80
        call 0x0024                     ; ENASLT
        di
        ld hl,0x8000                    ; the volume tables of the player (the music of the video is a stream of sample numbers)
        ld de,TABHI * 256
        ld bc,768
        ldir
        ld a,7                          ; PSG: tone and noise off, volumes 0
        out (0xA0),a
        ld a,0xBF
        out (0xA1),a
        xor a
        out (0xA1),a
        ld a,8
        out (0xA0),a
        xor a
        out (0xA1),a
        ld a,9
        out (0xA0),a
        xor a
        out (0xA1),a
        ld a,10
        out (0xA0),a
        xor a
        out (0xA1),a

menu:   call txmode
        ld hl,s_0
        ld de,0*40+1
        call puts
        ld hl,s_1
        ld de,3*40+1
        call puts
        ld hl,s_2
        ld de,5*40+1
        call puts
        ld hl,s_3
        ld de,7*40+1
        call puts
        ld hl,s_4
        ld de,9*40+1
        call puts
        ld hl,s_5
        ld de,12*40+1
        call puts
        ld hl,s_6
        ld de,15*40+1
        call puts
        ld a,(0x002D)
        add a,'0'
        out (0x98),a
        ld hl,s_7
        ld de,17*40+1
        call puts
.rel:   call keys                       ; wait until all keys 1..4 are up
        and 0x1E
        jr nz,.rel
.k:     call waitf
        call keys
        ld b,0
        bit 1,a
        jr nz,.go
        inc b
        bit 2,a
        jr nz,.go
        inc b
        bit 3,a
        jr nz,.go
        inc b
        bit 4,a
        jr z,.k
.go:    ld a,b
        add a,a
        ld l,a
        ld h,0
        ld de,vtab
        add hl,de
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        ld (lsel),hl
        call g2mode
        ld hl,(lsel)
        ld de,menu
        push de
        jp (hl)                         ; the video; it ends with SPACE, joystick fire or when the song is over (ret to menu)

keys:   in a,(0xAA)                     ; keyboard row 0: bit 1..4 = the keys 1..4 (1 = pressed)
        and 0xF0
        out (0xAA),a
        in a,(0xA9)
        cpl
        ret

waitf:  in a,(0x99)
.w:     in a,(0x99)
        rlca
        jr nc,.w
        ret

vregs:  ld b,8                          ; HL = 8 register values
        ld c,0x80
.v:     ld a,(hl)
        out (0x99),a
        ld a,c
        out (0x99),a
        inc hl
        inc c
        djnz .v
        ret

vset:   ld a,e
        out (0x99),a
        ld a,d
        or 0x40
        out (0x99),a
        ret
puts:   call vset
pstr:   ld a,(hl)
        or a
        ret z
        out (0x98),a
        inc hl
        jr pstr

txmode: ld hl,txregs                    ; text mode, name table at 0, font at 0800h
        call vregs
        call msx2regs
        ld de,0x0800
        call vset
        ld hl,(0x0004)                  ; the font of the BIOS
        ld bc,0x0800
.fl:    ld a,(hl)
        out (0x98),a
        inc hl
        dec bc
        ld a,b
        or c
        jr nz,.fl
        ld de,0
        call vset
        ld bc,960
.cl:    ld a,32
        out (0x98),a
        dec bc
        ld a,b
        or c
        jr nz,.cl
        ret

g2mode: ld hl,g2regs                    ; Graphics 2: the display is off while the tables are made
        call vregs
        call msx2regs
        ld de,0
        call vset
        ld bc,0x4000                    ; patterns, names and colours: 0
.z:     xor a
        out (0x98),a
        dec bc
        ld a,b
        or c
        jr nz,.z
        ld de,0x1800                    ; the name table: 0..255 three times
        call vset
        ld b,3
.n3:    xor a
.n:     out (0x98),a
        inc a
        jr nz,.n
        djnz .n3
        ld de,0x1B00                    ; no sprites
        call vset
        ld a,0xD0
        out (0x98),a
        ld a,0xC0                       ; display on
        out (0x99),a
        ld a,0x81
        out (0x99),a
        ret

msx2regs:                               ; MSX2 and later: R#15 = 0 (status register 0: the BIOS may leave another one selected) and R#14 = 0 (VRAM address bits 16..14)
        ld a,(0x002D)
        or a
        ret z                           ; (a TMS9918A would take these writes for R#7 / R#6)
        xor a
        out (0x99),a
        ld a,0x8F
        out (0x99),a
        xor a
        out (0x99),a
        ld a,0x8E
        out (0x99),a
        ret

g2regs: db 0x02,0x80,0x06,0xFF,0x03,0x36,0x07,0x01
txregs: db 0x00,0xD0,0x00,0x00,0x01,0x00,0x00,0xF4
vtab:   dw tvd0_tvplay, tvd4_tvplay, tvd8_tvplay, tvd11_tvplay
s_0:    db "PM LOGO + MUSIC TEST",0
s_1:    db "1 = LOOP 446 CYCLES (AS IN THE GAME)",0
s_2:    db "2 = LOOP 442 (4 SHORTER)",0
s_3:    db "3 = LOOP 438 (8 SHORTER)",0
s_4:    db "4 = LOOP 435 (11 SHORTER)",0
s_5:    db "SPACE OR FIRE ENDS THE LOGO",0
s_6:    db "MSXVER: ",0
s_7:    db "0=MSX1 1=MSX2 2=MSX2+ 3=TURBO R",0

        INCLUDE "tvplay_var.inc"
        ASSERT $ < 0x8000
        ds 0x8000-$,0xFF
        SAVEBIN "code.bin",0x4000,0x4000
