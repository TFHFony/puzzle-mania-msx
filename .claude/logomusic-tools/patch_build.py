"""one-time patch: tools/build_game.py --logotest (LOGOTEST equ in cfg.inc, the four speeds of the title video loop in game/tvplay_var.inc)"""
BS = chr(92)
p = r'F:\MSX Projects\PMdev26\tools\build_game.py'
s = open(p, encoding='utf8').read()
assert 'LOGOTEST' not in s
a = 'TIETONLY equ 0' + BS + 'nBUILDID'
assert s.count(a) == 1
s = s.replace(a, 'TIETONLY equ 0' + BS + 'nLOGOTEST equ %d' + BS + 'nBUILDID')
b = "PLR_BANK, (0 if lite else 2 if arg('--clipframes')"
assert s.count(b) == 1
s = s.replace(b, "PLR_BANK, 1 if '--logotest' in sys.argv else 0, (0 if lite else 2 if arg('--clipframes')")
c = "    gen = 'WELCOME equ %d"
assert s.count(c) == 1
s = s.replace(c, "    if '--logotest' in sys.argv:                                                # test ROM: only the PM logo with its music, the loop in four speeds (game/logotest.asm)\n"
                 "        import gen_tvplay\n"
                 "        txt = '; GENERATED by tools/build_game.py --logotest: the title video loop in four speeds (D = cycles less per loop)' + chr(10)\n"
                 "        for d in (0, 4, 8, 11):\n"
                 "            gen_tvplay.main(d, 'tvd%d_' % d, 'tvplay_tmp.inc')\n"
                 "            txt += open(os.path.join(PROJ, 'game', 'tvplay_tmp.inc')).read()\n"
                 "        os.remove(os.path.join(PROJ, 'game', 'tvplay_tmp.inc'))\n"
                 "        open(os.path.join(PROJ, 'game', 'tvplay_var.inc'), 'w').write(txt)\n" + c)
open(p, 'w', encoding='utf8').write(s)
print('ok')
