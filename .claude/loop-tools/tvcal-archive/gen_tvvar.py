"""Generates game/tvvar.asm (the variants of the title video player, one per 1 KB slot of a ROM bank, assembled for their place in the RAM: TVRAM),
game/tvcal.inc (constants) and game/tvtab.inc (the decision thresholds of the calibration, game/tvcal.asm).
Variant k has loops of 446 - D[k] cycles: a machine that runs the loop x % slower than the cycle count (VDP wait states of a turbo R, ...) needs a variant with D = 4.46 * x
cycles less to get the 8025 Hz of the music back.  The last slot is the calibration variant: one video frame of the bank TVZERO (zeros: silent), then it returns.
tools/tvcal.json: ref50 / ref60 = the value of the measurement (16 bit fraction) on a machine that runs the loop exactly as counted (openMSX, tools/tvcal_ref.py)."""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_tvplay
D = list(range(-6, 22, 2))                  # cycles less per loop
NV = len(D)                                 # the calibration variant is slot NV
D0 = D.index(0)
TVRAM = 0xE800
TNOM = 696793                               # cycles of one video frame of the loop (openMSX)
FRAME = {50: 313 * 228, 60: 262 * 228}


def main():
    ref = json.load(open(os.path.join(HERE, 'tvcal.json'))) if os.path.exists(os.path.join(HERE, 'tvcal.json')) else {'ref50': 15000, 'ref60': 21000}
    out = ['; GENERATED by tools/gen_tvvar.py - do not edit.', '        DEVICE NOSLOT64K', '        INCLUDE "equ.inc"', '        INCLUDE "tvcal.inc"']
    for k in range(NV + 1):
        if k < NV:
            L = gen_tvplay.gen(D[k], 'v%d_' % k, 'TVBANK', 'TVFRAMES', 'v%d' % k)
        else:
            L = gen_tvplay.gen(0, 'vc_', 'TVZERO', '1', 'vc')
        out.append('        ORG 0x%04X' % (0x4000 + 0x400 * k))
        out.append('        DISP TVRAM')
        out += L
        out.append('vend%d:' % k)
        out.append('        ASSERT vend%d - TVRAM <= 0x400' % k)
        out.append('        ENT')
    out.append('        SAVEBIN "tvvar.bin",0x4000,0x4000')
    open(os.path.join(PROJ, 'game', 'tvvar.asm'), 'w').write('\n'.join(out) + '\n')
    equ = ['; GENERATED by tools/gen_tvvar.py', 'TVRAM equ 0x%04X' % TVRAM, 'TV_NV equ %d' % NV, 'TV_D0 equ %d' % D0, 'TVREF50 equ %d' % ref['ref50'], 'TVREF60 equ %d' % ref['ref60']]
    open(os.path.join(PROJ, 'game', 'tvcal.inc'), 'w').write('\n'.join(equ) + '\n')
    tab = ['; GENERATED by tools/gen_tvvar.py: the 13 decision thresholds (+8000h) between the %d variants, D = %s' % (NV, D)]
    for hz in (50, 60):
        A = 446.0 * FRAME[hz] / TNOM                   # cycles of a loop per unit of 1/65536 frame... x = d * 65536 / A
        ts = []
        for j in range(NV - 1):
            d = D[j] + 1                               # the boundary between variant j and j + 1
            ts.append(max(0, min(65535, int(round(d * 65536 / A)) + 0x8000)))
        tab.append('tv_thr%d:' % hz)
        tab.append('        dw ' + ','.join(str(t) for t in ts))
    open(os.path.join(PROJ, 'game', 'tvtab.inc'), 'w').write('\n'.join(tab) + '\n')
    print('tvvar.asm: %d variants + calibration, D = %s' % (NV, D))


if __name__ == '__main__':
    main()
