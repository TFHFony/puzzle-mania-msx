; ------------------------------------------------------------------------------------------------ the player block (runs from RAM at PLAYER_RAM)
; volume tables, mvsync (slots.inc, generated), mnext.  Copied to the RAM at the start (the code bank only holds the vectors it needs).
        INCLUDE "psgtab.inc"            ; tabA..: 5 gain sets x 3 tables (generated); the SCC player needs them too: the title video plays its music on the PSG
        ASSERT $ == mvsync
        IF SCCPLAYER
        INCLUDE "slots_scc16.inc"       ; mvsync_ (generated by tools/gen_slots.py --scc16)
        ELSE
        INCLUDE "slots.inc"             ; mvsync_ (generated by tools/gen_slots.py): the volume writes of the loop after the slots close together
        ENDIF

jtab:   ; joystick -> keyboard row 8: bit 7 right, 6 down, 5 up, 4 left, low nibble 1 (index: bit 0 up, 1 down, 2 left, 3 right of PSG register 14)
        REPT 16, d
        db 0x0F | ((((d >> 3) & 1) << 7) | (((d >> 1) & 1) << 6) | ((d & 1) << 5) | (((d >> 2) & 1) << 4))
        ENDR

dirtab: ; the cursor keys that are down (index: bit 0 left, 1 up, 2 down, 3 right of row 8 inverted, high nibble) -> 1 up, 3 right, 5 down, 7 left; two keys or none: 0
        REPT 16, d
        db 0 - ((d == 2) * 1 + (d == 8) * 3 + (d == 4) * 5 + (d == 1) * 7)      ; (sjasmplus: true = -1)
        ENDR

wxtab:  db 0,81,71,169,158,164,71,169    ; FREE: work (in delay rounds of 13 cycles) that a frame of this busy level does beyond an idle one (measured: tools/.. t86.tcl)

rsetbank:                               ; HL = ROM bank in the page 2 window (8000h)
        ld a,l
        ld (0x7000),a
        ld a,h
        BANKHI 0x7001
        ret

mnext:  ld hl,(mus_bank)                ; next bank of the track; back to the start after the last one (or silence for a track that plays once)
        inc hl
        ld de,(mus_e)
        or a
        sbc hl,de
        jr nz,.nl
        ld a,(mus_lp)
        or a
        jr z,.once
        ld a,(mus_wr)                   ; the track starts again
        inc a
        ld (mus_wr),a
        ld hl,(mus_s)
        jr .st
.once:  ld a,1
        ld (mus_done),a
        ld hl,(mus_e)
        dec hl
        ld (mus_bank),hl
        call rsetbank
        ld hl,0xBF00                    ; the last 256 samples of a track that plays once are silence
        ret
.nl:    add hl,de
.st:    ld (mus_bank),hl
        call rsetbank
        ld hl,0x8000
        ret
