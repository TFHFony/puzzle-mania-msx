; PUZZLE MANIA - PM.wav sample test ROM: plays only the in-game music (the same PSG sample player as the game), for a real MSX.
; Page 1 = this code (bank 0), page 2 = NEO16 window: banks 1.. hold the music.  Tools: tools/build_sample.py (writes sgen.inc, psgtab.inc).
        DEVICE NOSLOT64K
        ORG 0x4000
        db "AB"
        dw init
        dw 0,0,0,0,0,0
        db "ROM_NE16"
        ORG 0x4020

        INCLUDE "equ.inc"
        INCLUDE "opts.inc"              ; SFRAMED, SJOB (generated by tools/build_sample.py)
        INCLUDE "heads.inc"
        INCLUDE "clk.inc"

init:   di
        ld sp,0xF380
        ld hl,0xC000
        ld de,0xC001
        ld bc,0x02FF
        ld (hl),0
        ldir
        ld hl,player_img
        ld de,PLAYER_RAM
        ld bc,player_img_end-player_img
        ldir
        xor a
        ld (0x6000),a                   ; page 1 window = bank 0
        ld (0x6001),a
        call 0x0138                     ; RSLREG: page 2 = our cartridge slot (same as page 1)
        rrca
        rrca
        and 3
        ld c,a
        ld b,0
        ld hl,0xFCC1
        add hl,bc
        or (hl)
        ld c,a
        inc hl
        inc hl
        inc hl
        inc hl
        ld a,(hl)
        and 0x0C
        or c
        ld h,0x80
        call 0x0024                     ; ENASLT
        di
        ld hl,(0x0004)                  ; BIOS font
        ld (v_font),hl
        ld a,2
        call CHGMOD                     ; SCREEN 2
        di
        ld a,0xC0
        out (0x99),a
        ld a,0x81
        out (0x99),a
        ld a,0x01
        out (0x99),a
        ld a,0x87
        out (0x99),a
        call nametab
        call sprpat
        ld a,(0x002B)                   ; 50 / 60 Hz
        rlca
        ld a,50
        jr c,.hz
        ld a,60
.hz:    ld (v_hz),a
        ld hl,0x1234
        ld (v_rng),hl
        ld a,0xFF
        ld (k8),a
        ld (k7),a
        ld (k3),a
        ld (k4),a
        ld (k5),a
        xor a
        ld (mus_on),a
        call clrscr
        ld hl,s_t1
        ld d,3
        ld e,10
        call boldtext
        ld hl,s_t2
        ld d,6
        ld e,2
        ld a,0xF1
        call text
        ld hl,s_t3
        ld d,9
        ld e,4
        ld a,0xB1
        call text
        ld hl,s_table
        ld d,9
        ld e,15
        ld a,0xF1
        call text
        ld hl,s_t4
        ld d,12
        ld e,4
        ld a,0xE1
        call text
        ld hl,s_t5
        ld d,14
        ld e,4
        ld a,0xE1
        call text
        ld hl,s_t6
        ld d,18
        ld e,4
        ld a,0xA1
        call text
        xor a
        ld c,0
        call music_play
        IF SFRAMED
        call job_reset
.l:     call mvsync                     ; the game player (calibration: tools/tune_slots.py)
        IF SJOB
        ld a,(j_qn)                     ; test job for the calibration of the job engine: 4 rows of 80 bytes into the pattern table, rows 20..23
        cp 2
        jr nc,.l
        ld hl,0x00B0                    ; source step at the end of a row: 256 - 80 (the image) / -80 (a blank block)
        ld (q_adj),hl
        ld hl,blank1
        ld de,0x5400
        ld b,80
        ld c,4
        call jq_put
        ld hl,0xFFB0
        ld (q_adj),hl
        ld hl,blank0
        ld de,0x5400
        ld b,80
        ld c,4
        call jq_put
        ENDIF
        IF SJOB == 0
        ld a,(sj_done)                  ; one shot, for the check of the engine (tools/check_engine.tcl): code bytes to rows 20..23, zeros to rows 12..15
        or a
        jr nz,.l
        inc a
        ld (sj_done),a
        ld hl,0x00B0
        ld (q_adj),hl
        ld hl,0x4100
        ld de,0x5400
        ld b,80
        ld c,4
        call jq_put
        ld hl,0x4100
        ld de,0x7400                    ; the same into the colour table, rows 20..23
        ld b,80
        ld c,4
        call jq_put
        ld hl,0xFFB0
        ld (q_adj),hl
        ld hl,blank0
        ld de,0x4C00
        ld b,80
        ld c,4
        call jq_put
        ENDIF
        jr .l
        ELSE
        jp music_free                   ; no frame lock, no gaps: the ideal player (listening test)
        ENDIF

music_free:                             ; endless loop, one sample every period, nothing else
        ld hl,(mus_bank)
        call setbank
        ld hl,0x8000
.s:     ld a,(hl)
        inc hl
        ld e,a
        ld a,(mus_tab)
        ld d,a
        ld a,8
        out (0xA0),a
        ld a,(de)
        out (0xA1),a
        inc d
        ld a,9
        out (0xA0),a
        ld a,(de)
        out (0xA1),a
        inc d
        ld a,10
        out (0xA0),a
        ld a,(de)
        out (0xA1),a
        ld a,h
        cp 0xC0
        jr c,.nw
        call mnext
.nw:    ld a,(mus_fr)
        ld b,a
        ld a,(mus_fi)
        add a,b
        ld (mus_fr),a
        jr c,.f
.f:     nop
        nop
        nop
        nop
        nop
        inc de
        inc de
        ld b,MDELAY
.t:     djnz .t
        nop
        nop
        jp .s

tick:   ret
sj_done equ 0xC164
puzlined: ret
drawall: ret
        INCLUDE "core.asm"
        INCLUDE "music.asm"
        INCLUDE "job.asm"

s_t1:   db "PM.WAV TEST",0
s_t2:   db "PUZZLE MANIA - IN-GAME MUSIC",0
s_t3:   db "PSG TABLE:",0
s_t4:   db "8 KHZ SAMPLE ON THE 3 PSG",0
s_t5:   db "CHANNELS, PLAYS IN A LOOP",0
s_t6:   db "NO KEYS: POWER OFF TO STOP",0
        INCLUDE "sgen.inc"              ; mustab, s_table (generated)
player_img:                             ; the player block: copied to the RAM at the start (like the game does from its ROM bank)
        PHASE PLAYER_RAM
        INCLUDE "player.asm"
        DEPHASE
player_img_end:
        ASSERT $ < 0x7EE0
        ds 0x7EE0-$,0xFF
        jp row                          ; the jump table of the player (same addresses as in the game)
        jp fadestep
        jp setbank
        jp vsync
        jp tick
        ds 0x8000-$,0xFF
        SAVEBIN "sample.bin",0x4000,0x4000
