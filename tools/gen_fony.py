"""Generates game/fony.inc (and fonyw.inc for a machine with a VDP wait state): the player of the FONY intro film (tools/fony_video.py), PSG music.
The film is a window of 16 x 9 characters (128 x 72 pixels) in the SCREEN 2 picture: video and PSG samples in one stream, like the title video (tools/gen_tvplay.py): every
iteration takes 446 cycles (8026 Hz): 1 sample byte and 8 VDP bytes.  One frame = 320 iterations (25.08 fps, PAL and NTSC alike: the loop counts cycles, not fields):
  H1 (SPACE?), H2 (fire?), 9 rows of: address iteration + 16 iterations of 8 pattern bytes, address iteration + 16 iterations of 8 colour bytes, end of row,
  P1, P2, P3: three iterations (a sample byte each) that find the next frame in the table (fy_tab: bank, address) and switch to it.
A ROM bank holds 6 frames (2624 bytes each).  Registers: HL stream, C = 98h, B = 128 at the start of a row segment (the 8 + 15 * 8 outi bring it back to 0), IYH / IXH = VRAM
address (high byte | 40h) of the pattern / colour row, DE = tables / burn, the alternate registers are free for the work of P1..P3.
tools/fony.json holds the burn corrections measured in openMSX (tools/tune_fony.py)."""
import os, json, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_tvplay as G
PERIOD, AUDIO, AUDIO_C, VOUT8, VOUT8_C = G.PERIOD, G.AUDIO, G.AUDIO_C, G.VOUT8, G.VOUT8_C
ROW0, ROWS = 7, 9                                 # the window: character rows 7..15, columns 8..23 (address low byte 64)
IYH0, IXH0 = 0x40 + ROW0, 0x60 + ROW0
IYH_END = 0x40 + ROW0 + ROWS
PAD = 18                                          # extra iterations per frame (320 - 302)


def main(DD=0, pfx='', outname='fony.inc'):
    adj = {}
    pj = os.path.join(HERE, 'fony.json')
    if os.path.exists(pj):
        adj = json.load(open(pj))
    lab = [0]

    def B(n):                                     # a burn with unique labels
        lines = G.burn(int(round(n)))
        out = []
        for l in lines:
            if '%d' in l:
                l = l % lab[0]
            out.append(l)
        if any('.bl' in l for l in lines):
            lab[0] += 1
        return out

    L = ['; GENERATED by tools/gen_fony.py - do not edit.', 'fony:']
    L += ['        in a,(0x99)', '        ld a,7', '        out (0xA0),a', '        ld a,0xBF', '        out (0xA1),a',
          '        ld c,0x98', '        ld b,0', '        ld a,0xFF', '        ld (tv_f),a',
          '        ld hl,(fy_base)', '        ld a,l', '        ld (0x7000),a', '        ld a,h', '        BANKHI 0x7001', '        ld hl,0x8000', '        jp fy_p1']
    # ---- P1, P2, P3: the next frame (the first sample bytes of the frame are played twice at the start: no harm)
    p1 = [('        exx', 5), ('        ld a,(tv_f)', 14), ('        inc a', 5), ('        cp FYFRAMES', 8), ('        jp nc,fy_exit', 11), ('        ld (tv_f),a', 14),
          ('        ld l,a', 5), ('        ld h,0', 8), ('        ld e,a', 5), ('        ld d,0', 8), ('        add hl,hl', 12), ('        add hl,de', 12), ('        ld de,fyp_tab', 11),
          ('        add hl,de', 12), ('        ld (fy_ptr),hl', 17), ('        exx', 5)]
    p2 = [('        exx', 5), ('        ld hl,(fy_ptr)', 17), ('        ld a,(hl)', 8), ('        inc hl', 7), ('        ld e,(hl)', 8), ('        inc hl', 7), ('        ld d,(hl)', 8),
          ('        ld (fy_st),de', 22), ('        ld de,(fy_base)', 22), ('        ld c,a', 5), ('        ld b,0', 8), ('        ex de,hl', 5), ('        add hl,bc', 12),
          ('        ld (fy_bk),hl', 17), ('        exx', 5)]
    p3 = [('        exx', 5), ('        ld hl,(fy_bk)', 17), ('        ld a,l', 5), ('        ld (0x7000),a', 14), ('        ld a,h', 5), ('        BANKHI 0x7001', 14), ('        exx', 5),
          ('        ld hl,(fy_st)', 17), ('        ld iyh,%d' % IYH0, 13), ('        ld ixh,%d' % IXH0, 13)]
    L.append('fy_pad:')                           # PAD iterations with a sample byte only (B counts down to 0 again, as the row segments need)
    L += AUDIO
    L += B(PERIOD - DD - AUDIO_C - 5 - 11 + adj.get('Q', 0))
    L += ['        dec b', '        jp nz,fy_pad']
    for name, work, key in (('fy_p1', p1, 'P1'), ('fy_p2', p2, 'P2'), ('fy_p3', p3, 'P3')):
        L.append('%s:' % name)
        L += AUDIO
        L += [l for l, _ in work]
        L += B(PERIOD - DD - AUDIO_C - sum(c for _, c in work) + adj.get(key, 0))
    # ---- H1: SPACE?
    L.append('fy_h1:')
    L += AUDIO
    L += ['        in a,(0xAA)', '        and 0xF0', '        or 8', '        out (0xAA),a', '        in a,(0xA9)', '        bit 0,a', '        jp z,fy_kexit']
    L += B(PERIOD - DD - AUDIO_C - 76 + adj.get('H1', 0))
    # ---- H2: joystick fire A
    L.append('fy_h2:')
    L += AUDIO
    L += ['        ld a,15', '        out (0xA0),a', '        in a,(0xA2)', '        and 0xBF', '        out (0xA1),a', '        ld a,14', '        out (0xA0),a',
          '        in a,(0xA2)', '        bit 4,a', '        jp z,fy_kexit']
    L += B(PERIOD - DD - AUDIO_C - 110 + adj.get('H2', 0))
    # ---- the rows
    L.append('fy_row:')
    for tab, reg in (('p', 'iyh'), ('c', 'ixh')):
        if tab == 'c':
            L.append('fy_sc:')
        L += AUDIO
        L += ['        ld a,64', '        out (0x99),a', '        ld a,%s' % reg, '        out (0x99),a', '        set 7,b']
        L += B(PERIOD - DD - AUDIO_C - (8 + 13 + 10 + 13 + 10) - VOUT8_C + adj.get('S', 0))
        L += VOUT8
        L.append('fy_n%s:' % tab)
        L += AUDIO
        L += B(PERIOD - DD - AUDIO_C - VOUT8_C - 11 + adj.get('N', 0))        # (a burn loop changes Z: before the outi, the last one sets Z when B has counted back to 0)
        L += VOUT8
        L += ['        jp nz,fy_n%s' % tab]
    # ---- the end of the row
    L.append('fy_e:')
    L += AUDIO
    L += ['        inc iyh', '        inc ixh', '        ld a,iyh', '        cp 0x%02X' % IYH_END, '        jp z,fy_end']
    L += B(PERIOD - DD - AUDIO_C - 10 - 10 - 10 - 8 - 11 - 11 + adj.get('E', 0))
    L += ['        jp fy_row']
    L.append('fy_end:')                           # (the iterations of the rows: 2 + 9 * 33 = 299; P1..P3 and PAD more iterations bring the frame to 320)
    L += ['        ld b,%d' % PAD]
    L += B(PERIOD - DD - AUDIO_C - 10 - 10 - 10 - 8 - 11 - 8 - 11 + adj.get('F', 0))
    L += ['        jp fy_pad']
    silence = ['        ld a,8', '        out (0xA0),a', '        ld a,(TABHI*256+0xC00)', '        out (0xA1),a', '        ld a,9', '        out (0xA0),a', '        ld a,(TABHI*256+0xD00)',
               '        out (0xA1),a', '        ld a,10', '        out (0xA0),a', '        ld a,(TABHI*256+0xE00)', '        out (0xA1),a']
    L.append('fy_exit:')                           # (the PSG stays at the level of silence)
    L += silence + ['        or a', '        ret']
    L.append('fy_kexit:')                          # a key: carry
    L += silence + ['        scf', '        ret']
    txt = '\n'.join(L) + '\n'
    if pfx:
        txt = re.sub(r'\b(fony|fy_p1|fy_p2|fy_p3|fy_h1|fy_h2|fy_row|fy_sc|fy_np|fy_nc|fy_e|fy_end|fy_pad|fy_exit|fy_kexit)\b', pfx + r'\1', txt)
    open(os.path.join(PROJ, 'game', outname), 'w').write(txt)
    print(outname, len(L), 'lines')


if __name__ == '__main__':
    main()
    main(8, 'w_', 'fonyw.inc')                     # the loop for a machine with a VDP wait state (8 cycles less per iteration)
