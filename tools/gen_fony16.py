"""Generates game/fony16.inc (and fony16w.inc for a machine with a VDP wait state): the player of the FONY intro film (tools/fony_video.py) for an SCC, 16 kHz.
Like tools/gen_tvplay16.py (every iteration takes 446 cycles and outputs TWO samples, 223 cycles apart; 5 VDP bytes before the second sample, 3 after it) with the window of
tools/gen_fony.py: 9 rows of 16 + 16 iterations of 8 bytes, 320 iterations per frame, P1 / P2 / P3 (the work of the next frame in the halves) instead of F1 / F2, 5 frames per bank.
Registers: as gen_tvplay16, B = 128 at the start of a row segment.  The burns (cycles) of every half are in tools/fony16.json (tools/tune_fony.py)."""
import os, json, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_tvplay16 as G
from gen_fony import ROW0, ROWS, IYH0, IXH0, IYH_END
CFG = os.path.join(HERE, 'fony16.json')
FETCH, SWSCC, SWCART, WRA, WRB, OUT5, OUT3 = G.FETCH, G.SWSCC, G.SWCART, G.WRA, G.WRB, G.OUT5, G.OUT3


def main(wait=False, pfx='', outname='fony16.inc'):
    cfg = json.load(open(CFG)) if os.path.exists(CFG) else {}
    if wait:
        cfg = G.wait_cfg(cfg)
    n = [0]

    def b(kind, half, default=20.0):
        n[0] += 1
        return G.burn(cfg.get('%s%d' % (kind, half), default), '%d' % n[0])

    L = ['; GENERATED by tools/gen_fony16.py - do not edit.', 'fony16:']
    L += ['        ld c,0x98', '        ld b,0', '        ld a,(scc_pg)', '        ld ixl,a', '        ld a,(cart_pg)', '        ld iyl,a',
          '        ld a,0xFF', '        ld (tv_f),a', '        ld hl,(fy_base)', '        ld a,l', '        ld (0x7000),a', '        ld a,h', '        BANKHI 0x7001', '        ld hl,0x8000',
          '        jp t16_p1']

    def it(kind, label, work1, work2, tail=()):
        L.append('%s:' % label)
        L.extend(FETCH + SWSCC + WRA + SWCART)
        L.append('.ma:')
        L.extend(work1[0])
        L.extend(b(kind, 1))
        L.extend(work1[1])
        L.extend(SWSCC + WRB + SWCART)
        L.append('.mb:')
        L.extend(work2[0])
        L.extend(b(kind, 2))
        L.extend(work2[1])
        L.extend(tail)

    # ---- P1, P2, P3: the next frame in the alternate registers (the first sample bytes of the frame are played twice at the start: no harm)
    it('p1', 't16_p1', (['        exx', '        ld a,(tv_f)', '        inc a', '        cp FYFRAMES16', '        jp nc,tv16_exit', '        ld (tv_f),a', '        ld l,a', '        ld h,0',
                         '        ld e,a', '        ld d,0', '        exx'], []),
       (['        exx', '        add hl,hl', '        add hl,de', '        ld de,fys_tab', '        add hl,de', '        ld (fy_ptr),hl', '        exx'], []))
    it('p2', 't16_p2', (['        exx', '        ld hl,(fy_ptr)', '        ld a,(hl)', '        inc hl', '        ld e,(hl)', '        inc hl', '        ld d,(hl)', '        ld (fy_st),de',
                         '        ld c,a', '        exx'], []),
       (['        exx', '        ld de,(fy_base)', '        ld b,0', '        ex de,hl', '        add hl,bc', '        ld (fy_bk),hl', '        exx'], []))
    it('p3', 't16_p3', (['        exx', '        ld hl,(fy_bk)', '        ld a,l', '        ld (0x7000),a', '        ld a,h', '        BANKHI 0x7001', '        exx'], []),
       (['        ld hl,(fy_st)', '        ld iyh,%d' % IYH0, '        ld ixh,%d' % IXH0], []))
    space = ['        in a,(0xAA)', '        and 0xF0', '        or 8', '        out (0xAA),a', '        in a,(0xA9)', '        bit 0,a', '        jp z,tv16_kexit']
    joy = ['        ld a,15', '        out (0xA0),a', '        in a,(0xA2)', '        and 0xBF', '        out (0xA1),a', '        ld a,14', '        out (0xA0),a',
           '        in a,(0xA2)', '        bit 4,a', '        jp z,tv16_kexit']
    it('h1', 't16_h1', ([], space), ([], []))
    it('h2', 't16_h2', ([], joy), ([], []))
    L.append('tv16_row:')
    for tab, reg in (('p', 'iyh'), ('c', 'ixh')):
        it('a' + tab, 't16_a%s' % tab, (['        ld a,64', '        out (0x99),a', '        ld a,%s' % reg, '        out (0x99),a', '        set 7,b'], []), ([], []))
        L.append('t16_n%s:' % tab)
        L.append('.n%s:' % tab)
        L.extend(FETCH + SWSCC + WRA + SWCART)
        L.append('.ma:')
        L.extend(b('n' + tab, 1))
        L.extend(OUT5)
        L.extend(SWSCC + WRB + SWCART)
        L.append('.mb:')
        L.extend(b('n' + tab, 2))
        L.extend(OUT3)
        L.append('        jp nz,.n%s' % tab)
        L.append('        ld a,r                          ; (the loop path has a jp: the same time)')
    L.append('t16_e:')                                # the end of the row: next row addresses; the last row: the next frame
    L.extend(FETCH + SWSCC + WRA + SWCART)
    L.append('.ma:')
    L.extend(['        inc iyh', '        inc ixh'])
    L.extend(b('e', 1))
    L.extend(SWSCC + WRB + SWCART)
    L.append('.mb:')
    L.extend(['        ld a,iyh', '        cp 0x%02X' % IYH_END])
    L.extend(['        jp z,t16_f1'])
    L.extend(b('e', 2))
    L.append('        jp tv16_row')
    L.append('t16_f1:')
    L.extend(b('e', 2))                       # (the same burn as the row end that did not jump: the same time)
    L.append('        jp t16_p1')
    silence = ['        ld a,(cart_pg)', '        out (0xA8),a']
    L.append('tv16_exit:')
    L.extend(silence + ['        or a', '        ret'])
    L.append('tv16_kexit:')
    L.extend(silence + ['        scf', '        ret'])
    txt = '\n'.join(L) + '\n'
    if pfx:
        txt = re.sub(r'\b(fony16|tv16_exit|tv16_kexit|tv16_row|t16_[a-z0-9]+)\b', pfx + r'\1', txt)
    open(os.path.join(PROJ, 'game', outname), 'w').write(txt)
    print(outname, len(L), 'lines')


if __name__ == '__main__':
    main()
    main(True, 'w_', 'fony16w.inc')
