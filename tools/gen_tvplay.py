"""Generates game/tvplay.inc: the player of the title video (tools/title_video.py): video and PSG samples in one stream, every iteration takes
446 cycles (8025 Hz): 1 sample byte (3 PSG volumes through the tables) and 8 VDP bytes (outi, a 'ld a,r' between them for the 30 cycles the VDP
wants).  The burns are computed from the cycles of the instructions (MSX: +1 per opcode fetch, +1 more for I/O); tools/tvplay.json holds the
corrections that were measured in openMSX (tools/tune_tv.py).
Registers: HL stream, C = 98h, B = 0 at the start of a row segment (the 8 + 31 * 8 outi bring it back to 0: the loop is 'jp nz'),
IYH = VRAM address (high byte | 40h) of the pattern row, IXH = the same for the colour row (+20h), DE = tables / burn."""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.dirname(HERE)
PERIOD = 446
OUTI, LDAR = 19, 11


def burn(n, e='e'):
    """asm lines that take exactly n cycles (E is free): loops of 18k+3, nops (5), inc de (7)"""
    if n <= 0:
        return []
    best = None
    for k in range(n // 18, -1, -1):
        base = 18 * k + 3 if k else 0
        rem = n - base
        if rem < 0:
            continue
        for b in range(0, rem // 7 + 1):
            if (rem - 7 * b) % 5 == 0:
                best = (k, (rem - 7 * b) // 5, b); break
        if best:
            break
    assert best, n
    k, a, b = best
    out = []
    if k:
        out += ['        ld %s,%d' % (e, k), '.bl%%d: dec %s' % e, '        jr nz,.bl%d']
    out += ['        nop'] * a + ['        inc de'] * b
    return out


AUDIO = ['        ld a,(hl)', '        inc hl', '        ld e,a', '        ld d,TABHI',
         '        ld a,8', '        out (0xA0),a', '        ld a,(de)', '        out (0xA1),a', '        inc d',
         '        ld a,9', '        out (0xA0),a', '        ld a,(de)', '        out (0xA1),a', '        inc d',
         '        ld a,10', '        out (0xA0),a', '        ld a,(de)', '        out (0xA1),a']
AUDIO_C = 164
VOUT8 = ['        outi'] + ['        ld a,r', '        outi'] * 7
VOUT8_C = 8 * OUTI + 7 * LDAR


def main():
    adj = {}
    pj = os.path.join(HERE, 'tvplay.json')
    if os.path.exists(pj):
        adj = json.load(open(pj))
    lab = [0]

    def B(n):                                     # a burn with unique labels
        lines = burn(int(round(n)))
        out = []
        for l in lines:
            if '%d' in l:
                l = l % lab[0]
            out.append(l)
        if any('.bl' in l for l in lines):
            lab[0] += 1
        return out

    L = []
    L.append('; GENERATED by tools/gen_tvplay.py - do not edit.')
    L.append('tvplay:')
    L += ['        in a,(0x99)', '        ld a,7', '        out (0xA0),a', '        ld a,0xBF', '        out (0xA1),a',          # mixer: tone and noise off, the channels only give their volume (music_play does this too)
          '        ld c,0x98', '        ld b,0', '        ld a,0xFF', '        ld (tv_f),a', '        jr tv_frame0']
    L.append('tv_frame0:')
    # ---- H1: next bank, HL = 8000h, rows from 0; SPACE?
    pre = [('        ld a,(tv_f)', 14), ('        inc a', 5), ('        cp TVFRAMES', 8), ('        jp nc,tv_exit', 11), ('        ld (tv_f),a', 14),
           ('        ld l,a', 5), ('        ld h,0', 8), ('        ld de,TVBANK', 11), ('        add hl,de', 12), ('        ld a,l', 5), ('        ld (0x7000),a', 14),
           ('        ld a,h', 5), ('        BANKHI 0x7001', 14), ('        ld hl,0x8000', 11), ('        ld iyh,0x40', 13), ('        ld ixh,0x60', 13)]
    pre_c = sum(c for _, c in pre)                  # (the video ends when the frame number runs out: tv_exit, then the caller goes on)
    L.append('tv_frame:')
    L += [l for l, _ in pre]
    L += AUDIO
    space = ['        in a,(0xAA)', '        and 0xF0', '        or 8', '        out (0xAA),a', '        in a,(0xA9)', '        bit 0,a', '        jp z,tv_exit']
    L += space
    L += B(PERIOD - AUDIO_C - 76 + adj.get('H1', 0))
    # ---- H2: joystick fire A
    L += AUDIO
    joy = ['        ld a,15', '        out (0xA0),a', '        in a,(0xA2)', '        and 0xBF', '        out (0xA1),a', '        ld a,14', '        out (0xA0),a',
           '        in a,(0xA2)', '        bit 4,a', '        jp z,tv_exit']
    L += joy
    L += B(PERIOD - AUDIO_C - 110 + adj.get('H2', 0))
    # ---- the rows
    L.append('tv_row:')
    for tab, reg in (('p', 'iyh'), ('c', 'ixh')):
        L += AUDIO
        L += ['        xor a', '        out (0x99),a', '        ld a,%s' % reg, '        out (0x99),a']
        L += B(PERIOD - AUDIO_C - 41 - VOUT8_C + adj.get('S', 0))
        L += VOUT8
        L.append('.n%s:' % tab)
        L += AUDIO
        L += B(PERIOD - AUDIO_C - VOUT8_C - 11 + adj.get('N', 0))        # (a burn loop changes Z: before the outi, the last one sets Z when B has counted back to 0)
        L += VOUT8
        L += ['        jp nz,.n%s' % tab]
    # ---- the end of the row
    L += AUDIO
    L += ['        inc iyh', '        inc ixh', '        ld a,iyh', '        cp 0x58', '        jp z,tv_end']
    L += B(PERIOD - AUDIO_C - 10 - 10 - 10 - 8 - 11 - 11 + adj.get('E', 0))
    L += ['        jp tv_row']
    L.append('tv_end:')
    L += B(PERIOD - AUDIO_C - 10 - 10 - 10 - 8 - 11 - 11 - pre_c + adj.get('F', 0))
    L += ['        jp tv_frame']
    L.append('tv_exit:')
    L += ['        ld a,8', '        out (0xA0),a', '        xor a', '        out (0xA1),a', '        ld a,9', '        out (0xA0),a', '        xor a', '        out (0xA1),a',
          '        ld a,10', '        out (0xA0),a', '        xor a', '        out (0xA1),a', '        ret']
    open(os.path.join(PROJ, 'game', 'tvplay.inc'), 'w').write('\n'.join(L) + '\n')
    print('tvplay.inc', len(L), 'lines')


if __name__ == '__main__':
    main()
